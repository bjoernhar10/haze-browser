"""Draws Haze's placeholder icon into build/src/chrome/app/theme/chromium/.

A neutral square with an "H", in every size and format Chromium ships its
product logo in. The letter is built from rectangles rather than a font, so the
output is identical on every machine and the patch that carries it can be
regenerated byte for byte.

TODO(step 30): delete this script once the real icon lands.

Usage: scripts/placeholder_icon.py <build/src>
"""

import io
import pathlib
import sys

from PIL import Image, ImageDraw

SQUARE = (0x3A, 0x3A, 0x3C, 0xFF)
LETTER = (0xF5, 0xF5, 0xF7, 0xFF)
CLEAR = (0, 0, 0, 0)
SUPERSAMPLE = 8


def _draw(size, square=SQUARE, letter=LETTER, margin=1 / 16):
  """Returns a size x size RGBA image of the icon."""
  big = size * SUPERSAMPLE
  image = Image.new('RGBA', (big, big), CLEAR)
  draw = ImageDraw.Draw(image)
  inset = round(big * margin)
  side = big - 2 * inset
  draw.rounded_rectangle((inset, inset, inset + side - 1, inset + side - 1),
                         radius=round(side * 0.22), fill=square)

  stem = side * 0.12
  height = side * 0.46
  width = side * 0.42
  bar = side * 0.10
  left = inset + (side - width) / 2
  top = inset + (side - height) / 2
  right = left + width
  draw.rectangle((left, top, left + stem, top + height), fill=letter)
  draw.rectangle((right - stem, top, right, top + height), fill=letter)
  middle = top + height / 2
  draw.rectangle((left, middle - bar / 2, right, middle + bar / 2),
                 fill=letter)
  return image.resize((size, size), Image.LANCZOS)


def _with_name_space(height, width, **colors):
  """The icon at the left of a wider canvas, for the logo-plus-name slots."""
  canvas = Image.new('RGBA', (width, height), CLEAR)
  canvas.paste(_draw(height, **colors), (0, 0))
  return canvas


def _png(image):
  out = io.BytesIO()
  image.save(out, 'PNG', optimize=True)
  return out.getvalue()


def _xpm(image):
  """Pillow cannot write XPM, so emit the palette and pixels by hand."""
  pixels = image.convert('RGBA')
  keys = '.#abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789'
  palette = {}
  rows = []
  for y in range(pixels.height):
    row = ''
    for x in range(pixels.width):
      r, g, b, a = pixels.getpixel((x, y))
      color = 'None' if a < 128 else '#%02X%02X%02X' % (r, g, b)
      if color not in palette:
        palette[color] = keys[len(palette)]
      row += palette[color]
    rows.append(row)
  lines = ['/* XPM */', 'static char *product_logo_32[] = {',
           '"%d %d %d 1",' % (pixels.width, pixels.height, len(palette))]
  lines += ['"%s c %s",' % (key, color) for color, key in palette.items()]
  lines += ['"%s",' % row for row in rows[:-1]] + ['"%s"' % rows[-1], '};', '']
  return '\n'.join(lines).encode()


def _ico(sizes=(16, 24, 32, 48, 64, 128, 256)):
  out = io.BytesIO()
  _draw(256).save(out, 'ICO', sizes=[(s, s) for s in sizes])
  return out.getvalue()


def _icns():
  out = io.BytesIO()
  _draw(1024, margin=0.1).save(out, 'ICNS')
  return out.getvalue()


def _svg():
  # Same geometry as _draw(), on a 256 grid.
  return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256">'
          '<rect x="16" y="16" width="224" height="224" rx="49.28" '
          'fill="#3A3A3C"/><g fill="#F5F5F7">'
          '<rect x="80.96" y="76.48" width="26.88" height="103.04"/>'
          '<rect x="148.16" y="76.48" width="26.88" height="103.04"/>'
          '<rect x="80.96" y="116.8" width="94.08" height="22.4"/>'
          '</g></svg>\n').encode()


def _files():
  mono = dict(square=(0, 0, 0, 0xFF), letter=CLEAR)
  light = dict(square=LETTER, letter=SQUARE)
  files = {}
  for size in (16, 24, 48, 64, 128, 256):
    files['chromium/product_logo_%d.png' % size] = _png(_draw(size))
  files['chromium/product_logo_22_mono.png'] = _png(_draw(22, **mono))
  files['chromium/product_logo.svg'] = _svg()
  # The intro page animates this; a placeholder has nothing to animate.
  files['chromium/product_logo_animation.svg'] = _svg()
  for size in (24, 48, 64, 128, 256):
    files['chromium/linux/product_logo_%d.png' % size] = _png(_draw(size))
  files['chromium/linux/product_logo_32.xpm'] = _xpm(_draw(32))

  for scale, factor in (('default_100_percent', 1), ('default_200_percent', 2)):
    for size in (16, 32):
      files['%s/chromium/product_logo_%d.png' % (scale, size)] = _png(
          _draw(size * factor))
    files['%s/chromium/product_logo_name_22.png' % scale] = _png(
        _with_name_space(22 * factor, 97 * factor))
    files['%s/chromium/product_logo_name_22_white.png' % scale] = _png(
        _with_name_space(22 * factor, 97 * factor, **light))
  for size in (16, 32):
    files['default_100_percent/chromium/linux/product_logo_%d.png' %
          size] = _png(_draw(size))

  for name in ('chromium', 'chromium_doc', 'chromium_pdf', 'app_list'):
    files['chromium/win/%s.ico' % name] = _ico()
  files['chromium/win/tiles/Logo.png'] = _png(_draw(600))
  files['chromium/win/tiles/SmallLogo.png'] = _png(_draw(176))

  files['chromium/mac/app.icns'] = _icns()
  appicon = 'chromium/mac/Assets.xcassets/AppIcon.appiconset/appicon_%d.png'
  for size in (16, 32, 64, 128, 256, 512, 1024):
    files[appicon % size] = _png(_draw(size, margin=0.1))
  iconset = 'chromium/mac/Assets.xcassets/Icon.iconset/'
  files[iconset + 'icon_256x256.png'] = _png(_draw(256, margin=0.1))
  files[iconset + 'icon_256x256@2x.png'] = _png(_draw(512, margin=0.1))
  return files


def main(argv):
  if len(argv) != 2:
    sys.exit(__doc__.strip().splitlines()[-1])
  theme = pathlib.Path(argv[1]) / 'chrome' / 'app' / 'theme'
  for relative, data in sorted(_files().items()):
    target = theme / relative
    if not target.exists():
      sys.exit('placeholder_icon.py: %s does not exist upstream' % target)
    target.write_bytes(data)
    print(relative)


if __name__ == '__main__':
  main(sys.argv)
